/**
 * MOOLA Unified Development Environment Launcher
 * 
 * Starts the Node/Express backend and Expo dev server simultaneously.
 * - Automatically detects local LAN IPv4 address (no manual IP editing!)
 * - Updates apps/mobile/.env.local with auto-detected LAN API URL
 * - Waits for backend + MongoDB Atlas to become healthy on port 5000
 * - Starts Expo in interactive mode (press 'w' for web in Chrome, scan QR on Android)
 * - Gracefully handles termination (Ctrl+C) on Windows and Unix
 */

const { spawn, execSync } = require('child_process');
const http = require('http');
const os = require('os');
const path = require('path');
const fs = require('fs');

const ROOT_DIR = path.resolve(__dirname, '..');
const MOBILE_DIR = path.join(ROOT_DIR, 'apps', 'mobile');
const SERVER_DIR = path.join(ROOT_DIR, 'apps', 'server');
const BACKEND_PORT = 5000;
const HEALTH_URL = `http://127.0.0.1:${BACKEND_PORT}/api/health`;

// ── 1. Detect LAN IPv4 Address ──────────────────────────────────
function getLanIp() {
  const interfaces = os.networkInterfaces();
  const candidates = [];

  for (const name of Object.keys(interfaces)) {
    const isVirtual = /vethernet|virtual|vmware|loopback|wsl|tailscale|tap/i.test(name);
    for (const iface of interfaces[name] || []) {
      if (iface.family === 'IPv4' && !iface.internal) {
        // Prioritize physical Wi-Fi and Ethernet adapters
        const isWifiOrEth = /wi-?fi|wireless|ethernet|wlan|en|eth/i.test(name);
        const isPrivate = /^(192\.168\.|10\.|172\.(1[6-9]|2\d|3[0-1])\.)/.test(iface.address);
        
        candidates.push({
          name,
          address: iface.address,
          score: (isWifiOrEth ? 10 : 0) + (isPrivate ? 5 : 0) - (isVirtual ? 20 : 0),
        });
      }
    }
  }

  candidates.sort((a, b) => b.score - a.score);
  return candidates.length > 0 ? candidates[0].address : 'localhost';
}

// ── 2. Check Backend Health ─────────────────────────────────────
function checkHealth() {
  return new Promise((resolve) => {
    const req = http.get(HEALTH_URL, (res) => {
      resolve(res.statusCode === 200);
    });
    req.on('error', () => resolve(false));
    req.setTimeout(1000, () => {
      req.destroy();
      resolve(false);
    });
  });
}

async function waitForBackend(maxAttempts = 60, intervalMs = 500) {
  process.stdout.write('⏳ Waiting for MOOLA backend & MongoDB Atlas to be ready...');
  for (let i = 0; i < maxAttempts; i++) {
    const healthy = await checkHealth();
    if (healthy) {
      console.log(' [READY]');
      return true;
    }
    process.stdout.write('.');
    await new Promise((r) => setTimeout(r, intervalMs));
  }
  console.log(' [TIMEOUT]');
  return false;
}

// ── 3. Graceful Process Cleanup ─────────────────────────────────
const childProcesses = [];

function killProcess(proc) {
  if (!proc || proc.killed) return;
  try {
    if (process.platform === 'win32') {
      try {
        execSync(`taskkill /pid ${proc.pid} /T /F`, { stdio: 'ignore' });
      } catch {
        proc.kill();
      }
    } else {
      proc.kill('SIGTERM');
    }
  } catch {}
}

function cleanup() {
  console.log('\n🛑 Stopping MOOLA development services...');
  for (const proc of childProcesses) {
    killProcess(proc);
  }
  process.exit(0);
}

process.on('SIGINT', cleanup);
process.on('SIGTERM', cleanup);

// ── 4. Main Development Workflow ────────────────────────────────
async function main() {
  console.log('\n🌿 ═══════════════════════════════════════════════════════════════');
  console.log('🌿  MOOLA — Local Development Environment');
  console.log('🌿  Chrome Browser + Android Mobile Simultaneous Setup');
  console.log('🌿 ═══════════════════════════════════════════════════════════════\n');

  // Detect and configure LAN IP
  const lanIp = getLanIp();
  console.log(`📡 Detected Host LAN IP: ${lanIp}`);

  // Write/update apps/mobile/.env.local so Metro injects EXPO_PUBLIC_DEV_API_URL
  const mobileEnvLocalPath = path.join(MOBILE_DIR, '.env.local');
  const envContent = [
    '# Auto-generated by scripts/dev.js on startup',
    `EXPO_PUBLIC_DEV_API_URL=http://${lanIp}:${BACKEND_PORT}/api/v1`,
    `REACT_NATIVE_PACKAGER_HOSTNAME=${lanIp}`,
    '',
  ].join('\n');
  fs.writeFileSync(mobileEnvLocalPath, envContent, 'utf-8');
  console.log(`📝 Dynamic Mobile API URL configured: http://${lanIp}:${BACKEND_PORT}/api/v1`);
  console.log(`📡 Packager Hostname configured: ${lanIp}`);

  // Check if backend is already running
  const alreadyRunning = await checkHealth();
  let serverProcess = null;

  if (alreadyRunning) {
    console.log(`✅ MOOLA backend is already running on port ${BACKEND_PORT}. Reusing existing instance.\n`);
  } else {
    console.log(`🚀 Starting MOOLA backend server on port ${BACKEND_PORT}...`);
    const npmCmd = process.platform === 'win32' ? 'npm.cmd' : 'npm';
    
    serverProcess = spawn(npmCmd, ['run', 'dev'], {
      cwd: SERVER_DIR,
      stdio: ['ignore', 'pipe', 'pipe'],
      shell: true,
      env: { ...process.env, PORT: String(BACKEND_PORT) },
    });

    childProcesses.push(serverProcess);

    // Stream backend logs with prefix
    serverProcess.stdout.on('data', (data) => {
      const lines = data.toString().trim().split('\n');
      for (const line of lines) {
        if (line.trim()) console.log(`[Backend] ${line}`);
      }
    });

    serverProcess.stderr.on('data', (data) => {
      const lines = data.toString().trim().split('\n');
      for (const line of lines) {
        if (line.trim()) console.error(`[Backend ERR] ${line}`);
      }
    });

    serverProcess.on('exit', (code) => {
      if (code !== 0 && code !== null) {
        console.error(`❌ Backend exited with code ${code}`);
      }
    });

    // Wait until backend and MongoDB Atlas are verified ready
    const isReady = await waitForBackend();
    if (!isReady) {
      console.error('\n❌ Backend failed to become healthy within 30 seconds.');
      console.error('Check your MongoDB Atlas connection in apps/server/.env or view logs above.');
      cleanup();
      return;
    }
  }

  // Print connection summary
  console.log('\n🌿 ─────────────────────────────────────────────────────────────');
  console.log('🌿 MOOLA DEVELOPMENT SERVICES READY:');
  console.log(`🌿   💻 Laptop Browser (Chrome): http://localhost:8081 (or press 'w')`);
  console.log(`🌿   📱 Android Mobile (Expo Go): Scan the QR code below`);
  console.log(`🌿   🚀 Backend API (Localhost):  http://localhost:${BACKEND_PORT}/api/v1`);
  console.log(`🌿   📱 Backend API (Mobile LAN): http://${lanIp}:${BACKEND_PORT}/api/v1`);
  console.log(`🌿   🩺 Health Check:             ${HEALTH_URL}`);
  console.log('🌿 ─────────────────────────────────────────────────────────────\n');

  // Start Expo dev server
  console.log('🚀 Starting Expo Development Server (Metro)...\n');
  const npxCmd = process.platform === 'win32' ? 'npx.cmd' : 'npx';

  // We start expo in interactive mode so user sees the QR code and can press 'w' for Chrome
  const expoProcess = spawn(npxCmd, ['expo', 'start', '--host', 'lan'], {
    cwd: MOBILE_DIR,
    stdio: 'inherit',
    shell: true,
    env: {
      ...process.env,
      REACT_NATIVE_PACKAGER_HOSTNAME: lanIp,
    },
  });

  childProcesses.push(expoProcess);

  expoProcess.on('exit', (code) => {
    console.log(`\nExpo server stopped with code ${code}`);
    cleanup();
  });
}

if (require.main === module) {
  main().catch((err) => {
    console.error('Startup error:', err);
    cleanup();
  });
} else {
  module.exports = { getLanIp, checkHealth };
}

